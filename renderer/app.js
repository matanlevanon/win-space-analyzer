window.api.onUpdateStatus((data) => {
  if (!data) return;
  switch (data.status) {
    case 'checking':
      el.aboutUpdateStatus.textContent = t('checking');
      break;
    case 'available':
      updateState.pendingVersion = data.version;
      el.versionPill.classList.add('has-update');
      el.aboutUpdateStatus.textContent = t('vAvailable', { v: data.version });
      showUpdateBanner(t('updAvailable', { v: data.version }), t('updDownload'), async () => {
        showUpdateBanner(t('updDownloading', { p: 0 }), null, null);
        await window.api.downloadUpdate();
      });
      break;
    case 'none':
      el.aboutUpdateStatus.textContent = t('upToDate');
      break;
    case 'progress':
      el.aboutUpdateStatus.textContent = t('updDownloading', { p: data.percent });
      showUpdateBanner(t('updDownloading', { p: data.percent }), null, null);
      break;
    case 'downloaded':
      el.aboutUpdateStatus.textContent = t('updReady', { v: data.version });
      showUpdateBanner(t('updReady', { v: data.version }), t('updInstall'), () => {
        window.api.installUpdate();
      });
      break;
    case 'error':
      // Silent - don't bother the user about a failed automatic check
      break;
  }
});

