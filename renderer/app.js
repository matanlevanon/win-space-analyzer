// ---------- Utils ----------
function formatSize(bytes) {
  bytes = Number(bytes) || 0;
  const TB = 1024 ** 4, MB = 1024 ** 2, KB = 1024;
  if (bytes >= TB) return (bytes / TB).toFixed(2) + ' TB';
  if (bytes >= GB) return (bytes / GB).toFixed(2) + ' GB';
  if (bytes >= MB) return (bytes / MB).toFixed(1) + ' MB';
  if (bytes >= KB) return (bytes / KB).toFixed(0) + ' KB';
  return bytes + ' B';
}
function thresholdBytes() { return state.thresholdGB * GB; }
function sanitizeId(id) { return String(id).replace(/[^A-Za-z0-9]/g, '') || 'x'; }
function fmtInt(n) { return Number(n).toLocaleString(window.I18N.locale()); }

// Localized display name for tree nodes whose names are generated by the scanner.
function dispName(n) {
  if (!n) return '';
  if (n.type === 'files-here') return t('filesHere');
  if (n.type === 'more-bucket') {
    const count = (typeof n.itemCount === 'number') ? n.itemCount : null;
    if (count !== null) return t('moreItems', { n: fmtInt(count) });
  }
  return n.name;
}

// Virtual "all drives" root has no path and no driveId.
function isVirtualRoot(n) { return n && !n.driveId && !n.path && Array.isArray(n.children); }
function rootLabel(n) {
  if (isVirtualRoot(n)) return t('allDrives');
  return n.displayName || n.name;
}

function driveTypeName(driveType) {
  switch (Number(driveType)) {
    case 2: return t('typeRemovable');
    case 3: return t('typeFixed');
    case 4: return t('typeNetwork');
    case 5: return t('typeCD');
    default: return t('typeOther');
  }
}

function relativeTime(iso) {
  if (!iso) return '';
  const then = new Date(iso).getTime();
  const s = Math.max(0, (Date.now() - then) / 1000);
  if (s < 60) return t('justNow');
  const m = Math.floor(s / 60); if (m < 60) return t('minAgo', { n: m });
  const h = Math.floor(m / 60); if (h < 24) return t('hrAgo', { n: h });
  const d = Math.floor(h / 24); if (d === 1) return t('yesterday');
  if (d < 30) return t('daysAgo', { n: d });
  const mo = Math.floor(d / 30); if (mo < 12) return t('moAgo', { n: mo });
  return t('overYear');
}

function showView(name) {
  el.viewHome.hidden = name !== 'home';
  el.viewScanning.hidden = name !== 'scanning';
  el.viewResults.hidden = name !== 'results';
  el.btnHome.hidden = name === 'home';
  el.btnBackResults.hidden = !(name === 'home' && state.hasResults);
}

let toastTimer = null;
function toast(msg) {
  el.toast.textContent = msg;
  el.toast.hidden = false;
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => { el.toast.hidden = true; }, 2600);
}

// ---------- Drives (home) ----------
async function loadDrives() {
  // Placeholder only when the cache is empty - avoids flicker on refresh
  if (!state.drives.length) {
    el.drivesList.innerHTML = '<div class="empty-state">' + t('loadingDrives') + '</div>';
  }
  const [drives, scans] = await Promise.all([window.api.listDrives(), window.api.listScans()]);
  state.drives = drives;
  state.scans = scans || {};
  renderDrives();
  renderVolumeStrip(); // keep the results-view strip in sync with fresh free-space data
}

// Back to home with refreshed drives + scan status (and updated free space)
function goHome() {
  showView('home');
  loadDrives();
}

